async function seed() {
  try {
    console.log('Connecting to MongoDB...');
    await mongoose.connect(process.env.MONGODB_URI);

    // Drop problematic non-sparse index on sourceLeadId if it exists
    try {
      console.log('Fixing sourceLeadId index to be sparse...');
      await mongoose.connection.collection('customers').dropIndex('sourceLeadId_1');
      await mongoose.connection.collection('customers').createIndex(
        { sourceLeadId: 1 },
        { unique: true, sparse: true, background: true }
      );
    } catch (e) {
      console.log('Index update notice:', e.message);
    }

    // Get an assigned staff user
    const staffUser = await User.findOne({ status: 'active' });
    const staffId = staffUser ? staffUser._id : null;

    // Clear existing customers to guarantee clean IDs and avoid duplicate key errors
    console.log('Clearing old customers...');
    await Customer.deleteMany({});

    console.log('Inserting 25 realistic customer records...');
    let index = 1;
    for (const c of customersData) {
      const customerId = `CUS-2026-${String(index).padStart(5, '0')}`;
      const customer = new Customer({
        ...c,
        customerId,
        assignedStaff: staffId,
      });
      await customer.save();
      index++;
    }

    console.log('Successfully seeded 25 customers matching design reference!');
    process.exit(0);
  } catch (err) {
    console.error('Failed to seed customers:', err);
    process.exit(1);
  }
}

seed();
